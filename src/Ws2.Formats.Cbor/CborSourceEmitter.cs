using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace Ws2.Formats.Cbor;

internal static class CborSourceEmitter
{
    internal static string Emit(SerializationContext model, CancellationToken cancellationToken)
    {
        StringBuilder b = new();
        var prefix = model.GeneratedPrefix;
        b.AppendLine("// <auto-generated/>");
        b.AppendLine("#nullable enable");
        if (model.Namespace.Length > 0)
        {
            b.Append("namespace ").Append(model.Namespace).AppendLine(";").AppendLine();
        }

        b.Append("partial ").Append(model.DeclarationKind).Append(' ').Append(EscapeIdentifier(model.ClassName)).AppendLine().AppendLine("{");
        for (var i = 0; i < model.Properties.Count; i++)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var property = model.Properties[i];
            if (property.ConverterTypeName is null)
            {
                continue;
            }

            b.Append("    private static readonly global::Ws2.Formats.Cbor.ICborConverter<")
                .Append(property.TypeName).Append("> ").Append(prefix).Append("Converter").Append(i).Append(" = new ")
                .Append(property.ConverterTypeName).AppendLine("();");
        }

        if (model.Properties.Any(static property => property.ConverterTypeName is not null))
        {
            b.AppendLine();
        }

        if (model.Properties.Any(static property => property.Kind == CborValueKind.Collection && property.ConverterTypeName is null))
        {
            b.AppendLine(
                    $"    private static global::System.Collections.Generic.List<T> {prefix}ReadCollection<T>(global::System.Formats.Cbor.CborReader reader, global::System.Func<global::System.Formats.Cbor.CborReader, T> readElement)")
                .AppendLine("    {")
                .AppendLine("        var length = reader.ReadStartArray();")
                .AppendLine(
                    "        if (length is null) throw new global::System.Formats.Cbor.CborContentException(\"Indefinite collection arrays are not supported.\");")
                .AppendLine("        var values = new global::System.Collections.Generic.List<T>();")
                .AppendLine("        for (var i = 0; i < length.Value; i++) values.Add(readElement(reader));")
                .AppendLine("        reader.ReadEndArray();")
                .AppendLine("        return values;")
                .AppendLine("    }").AppendLine();
        }

        if (model.Properties.Any(static property => RequiresCheckedRead(property.Kind) ||
            property.ConverterTypeName is null && property.Kind == CborValueKind.Collection && RequiresCheckedRead(property.ElementKind!.Value)))
        {
            b.AppendLine($"    private static T {prefix}ReadChecked<T>(string propertyName, global::System.Func<T> read)")
                .AppendLine("    {")
                .AppendLine("        try { return read(); }")
                .AppendLine("        catch (global::System.OverflowException exception)")
                .AppendLine("        {")
                .AppendLine(
                    "            throw new global::System.Formats.Cbor.CborContentException($\"CBOR value for property '{propertyName}' is outside its supported range.\", exception);")
                .AppendLine("        }")
                .AppendLine("    }").AppendLine();
        }

        if (model.Properties.Any(static property => property.ConverterTypeName is null &&
            (property.IsNullableValueType || property.Kind == CborValueKind.Collection && property.IsElementNullableValueType)))
        {
            b.AppendLine(
                    $"    private static T? {prefix}ReadNullableValue<T>(global::System.Formats.Cbor.CborReader reader, global::System.Func<global::System.Formats.Cbor.CborReader, T> read) where T : struct")
                .AppendLine("    {")
                .AppendLine(
                    "        if (reader.PeekState() == global::System.Formats.Cbor.CborReaderState.Null) { reader.ReadNull(); return default; }")
                .AppendLine("        return read(reader);")
                .AppendLine("    }").AppendLine();
        }

        if (model.Properties.Any(static property => property.ConverterTypeName is null &&
            (property.IsNullable && !property.IsNullableValueType ||
                property.Kind == CborValueKind.Collection && property.IsElementNullable && !property.IsElementNullableValueType)))
        {
            b.AppendLine(
                    $"    private static T? {prefix}ReadNullableReference<T>(global::System.Formats.Cbor.CborReader reader, global::System.Func<global::System.Formats.Cbor.CborReader, T> read) where T : class")
                .AppendLine("    {")
                .AppendLine(
                    "        if (reader.PeekState() == global::System.Formats.Cbor.CborReaderState.Null) { reader.ReadNull(); return null; }")
                .AppendLine("        return read(reader);")
                .AppendLine("    }").AppendLine();
        }

        if (model.Properties.Any(static property => property.ConverterTypeName is not null && property.IsNullable))
        {
            b.AppendLine(
                    $"    private static T {prefix}ReadNullableConverted<T>(global::System.Formats.Cbor.CborReader reader, global::System.Func<global::System.Formats.Cbor.CborReader, T> read)")
                .AppendLine("    {")
                .AppendLine(
                    "        if (reader.PeekState() == global::System.Formats.Cbor.CborReaderState.Null) { reader.ReadNull(); return default!; }")
                .AppendLine("        return read(reader);")
                .AppendLine("    }").AppendLine();
        }

        if (model.Properties.Any(static property => property.IsReferenceType && !property.IsNullable ||
            property.Kind == CborValueKind.Collection && property.IsElementReferenceType && !property.IsElementNullable))
        {
            b.AppendLine(
                    $"    private static T {prefix}ReadNonNull<T>(global::System.Formats.Cbor.CborReader reader, string propertyName, global::System.Func<global::System.Formats.Cbor.CborReader, T> read)")
                .AppendLine("    {")
                .AppendLine(
                    "        if (reader.PeekState() == global::System.Formats.Cbor.CborReaderState.Null) { reader.ReadNull(); throw new global::System.Formats.Cbor.CborContentException($\"CBOR null is not valid for property '{propertyName}'.\"); }")
                .AppendLine("        return read(reader);")
                .AppendLine("    }").AppendLine();
        }

        if (model.Properties.Any(static property => property.ConverterTypeName is not null && !property.IsNullable))
        {
            b.AppendLine($"    private static T {prefix}ReadConverted<T>(string propertyName, global::System.Func<T> read)")
                .AppendLine("    {")
                .AppendLine("        var value = read();")
                .AppendLine(
                    "        if (value is null) throw new global::System.Formats.Cbor.CborContentException($\"CBOR converter returned null for non-nullable property '{propertyName}'.\");")
                .AppendLine("        return value;")
                .AppendLine("    }").AppendLine();
        }

        if (model.Format == CborSerializationFormat.Map)
        {
            EmitMap(b, model, cancellationToken);
        }
        else
        {
            EmitArray(b, model, cancellationToken);
        }

        b.AppendLine("}");
        return b.ToString();
    }

    private static void EmitArray(StringBuilder b, SerializationContext model, CancellationToken cancellationToken)
    {
        (SerializableProperty property, int sourceIndex)[] propertiesByIndex =
        [
            .. model.Properties
                .Select((property, sourceIndex) => (property, sourceIndex))
                .OrderBy(static item => item.property.CborArrayIndex!.Value)
        ];

        b.AppendLine("    public void Serialize(global::System.Formats.Cbor.CborWriter writer)")
            .AppendLine("    {")
            .Append("        writer.WriteStartArray(").Append(model.Properties.Count).AppendLine(");");

        foreach (var item in propertiesByIndex)
        {
            cancellationToken.ThrowIfCancellationRequested();
            EmitWrite(b, item.property, item.sourceIndex, model.GeneratedPrefix);
        }

        b.AppendLine("        writer.WriteEndArray();").AppendLine("    }").AppendLine();
        b.Append("    public static ").Append(EscapeIdentifier(model.ClassName))
            .AppendLine(" Parse(global::System.Formats.Cbor.CborReader reader)")
            .AppendLine("    {")
            .AppendLine("        var length = reader.ReadStartArray();")
            .Append("        if (length != ").Append(model.Properties.Count)
            .AppendLine(" ) throw new global::System.Formats.Cbor.CborContentException(\"Unexpected CBOR array length.\");")
            .AppendLine();

        for (var i = 0; i < model.Properties.Count; i++)
        {
            cancellationToken.ThrowIfCancellationRequested();
            b.Append("        ").Append(model.Properties[i].TypeName).Append(" property").Append(i).AppendLine(" = default!;");
        }

        foreach (var item in propertiesByIndex)
        {
            cancellationToken.ThrowIfCancellationRequested();
            b.Append("        property").Append(item.sourceIndex).Append(" = ")
                .Append(EmitRead(item.property, item.sourceIndex, model.GeneratedPrefix)).AppendLine(";");
        }

        b.AppendLine("        reader.ReadEndArray();");
        EmitConstructorReturn(b, model);

        b.AppendLine("    }").AppendLine();
    }

    private static void EmitMap(StringBuilder b, SerializationContext model, CancellationToken cancellationToken)
    {
        b.AppendLine("    public void Serialize(global::System.Formats.Cbor.CborWriter writer)")
            .AppendLine("    {")
            .Append("        writer.WriteStartMap(").Append(model.Properties.Count).AppendLine(");");

        foreach (var propertyIndex in model.MapPropertyIndexes)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var property = model.Properties[propertyIndex];
            b.Append("        writer.WriteTextString(\"").Append(EscapeString(property.CborMapKey ?? property.Name)).AppendLine("\");");
            EmitWrite(b, property, propertyIndex, model.GeneratedPrefix);
        }

        b.AppendLine("        writer.WriteEndMap();").AppendLine("    }").AppendLine();
        b.Append("    public static ").Append(EscapeIdentifier(model.ClassName))
            .AppendLine(" Parse(global::System.Formats.Cbor.CborReader reader)")
            .AppendLine("    {")
            .AppendLine("        reader.ReadStartMap();")
            .AppendLine("        var seenKeys = new global::System.Collections.Generic.HashSet<string>(global::System.StringComparer.Ordinal);");

        for (var i = 0; i < model.Properties.Count; i++)
        {
            cancellationToken.ThrowIfCancellationRequested();
            b.Append("        ").Append(model.Properties[i].TypeName).Append(" property").Append(i).AppendLine(" = default!;")
                .Append("        var hasProperty").Append(i).AppendLine(" = false;");
        }

        b.AppendLine("        while (reader.PeekState() != global::System.Formats.Cbor.CborReaderState.EndMap)")
            .AppendLine("        {")
            .AppendLine("            var key = reader.ReadTextString();")
            .AppendLine(
                "            if (!seenKeys.Add(key)) throw new global::System.Formats.Cbor.CborContentException(\"Duplicate CBOR map key.\");")
            .AppendLine("            switch (key)")
            .AppendLine("            {");

        foreach (var propertyIndex in model.MapPropertyIndexes)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var property = model.Properties[propertyIndex];
            b.Append("                case \"").Append(EscapeString(property.CborMapKey ?? property.Name)).AppendLine("\":")
                .Append("                    property").Append(propertyIndex).Append(" = ")
                .Append(EmitRead(property, propertyIndex, model.GeneratedPrefix))
                .AppendLine(";")
                .Append("                    hasProperty").Append(propertyIndex).AppendLine(" = true;")
                .AppendLine("                    break;");
        }

        b.AppendLine("                default:")
            .AppendLine("                    reader.SkipValue();")
            .AppendLine("                    break;")
            .AppendLine("            }")
            .AppendLine("        }");

        for (var i = 0; i < model.Properties.Count; i++)
        {
            cancellationToken.ThrowIfCancellationRequested();
            b.Append("        if (!hasProperty").Append(i)
                .AppendLine(") throw new global::System.Formats.Cbor.CborContentException(\"Missing CBOR map key.\");");
        }

        b.AppendLine("        reader.ReadEndMap();");
        EmitConstructorReturn(b, model);

        b.AppendLine("    }").AppendLine();
    }

    private static void EmitConstructorReturn(StringBuilder b, SerializationContext model)
    {
        if (model.UsePropertyInitializer)
        {
            b.Append("        return new ").Append(EscapeIdentifier(model.ClassName)).AppendLine("()")
                .AppendLine("        {");

            for (var i = 0; i < model.Properties.Count; i++)
            {
                b.Append("            ").Append(EscapeIdentifier(model.Properties[i].Name)).Append(" = property")
                    .Append(i).AppendLine(i == model.Properties.Count - 1 ? string.Empty : ",");
            }

            b.AppendLine("        };");
            return;
        }

        if (model.ConstructorPropertyIndexes.Count == 0)
        {
            b.Append("        return new ").Append(EscapeIdentifier(model.ClassName)).AppendLine("();");
            return;
        }

        b.Append("        return new ").Append(EscapeIdentifier(model.ClassName)).AppendLine("(");
        for (var i = 0; i < model.ConstructorPropertyIndexes.Count; i++)
        {
            b.Append("            property").Append(model.ConstructorPropertyIndexes[i])
                .AppendLine(i == model.ConstructorPropertyIndexes.Count - 1 ? ");" : ",");
        }
    }

    private static string EscapeString(string value)
    {
        var literal = SyntaxFactory.Literal(value).Text;
        return literal.Substring(1, literal.Length - 2);
    }

    private static string EscapeIdentifier(string value)
    {
        return SyntaxFacts.GetKeywordKind(value) != SyntaxKind.None ||
            SyntaxFacts.GetContextualKeywordKind(value) != SyntaxKind.None
                ? "@" + value
                : value;
    }

    private static bool RequiresCheckedRead(CborValueKind kind)
    {
        return kind is CborValueKind.Byte or CborValueKind.SByte or CborValueKind.Int16 or CborValueKind.UInt16 or
            CborValueKind.Int32 or CborValueKind.UInt32 or CborValueKind.Int64 or CborValueKind.UInt64 or CborValueKind.Enum;
    }

    private static void EmitWrite(StringBuilder b, SerializableProperty property, int index, string prefix)
    {
        var propertyAccess = "this." + EscapeIdentifier(property.Name);
        var value = "value" + index;
        b.Append("        var ").Append(value).Append(" = ").Append(propertyAccess).AppendLine(";");
        if (property.IsNullable)
        {
            b.Append("        if (").Append(value).AppendLine(" is null)")
                .AppendLine("        {")
                .AppendLine("            writer.WriteNull();")
                .AppendLine("        }")
                .AppendLine("        else")
                .AppendLine("        {");

            EmitNonNullWrite(b, property, index, prefix, value, "            ");
            b.AppendLine("        }");
            return;
        }

        if (property.IsReferenceType)
        {
            b.Append("        if (").Append(value).Append(" is null) throw new global::System.ArgumentNullException(nameof(")
                .Append(propertyAccess).AppendLine("));");
        }

        EmitNonNullWrite(b, property, index, prefix, value, "        ");
    }

    private static void EmitNonNullWrite(
        StringBuilder b, SerializableProperty property, int index, string prefix, string value, string indentation
    )
    {
        if (property.IsNullableValueType)
        {
            value += ".Value";
        }

        if (property.ConverterTypeName is not null)
        {
            b.Append(indentation).Append(prefix).Append("Converter").Append(index).Append(".Write(writer, ").Append(value).AppendLine(");");
            return;
        }

        if (property.Kind == CborValueKind.Collection)
        {
            var count = property.CollectionKind == CborCollectionKind.Array ? value + ".Length" : value + ".Count";
            b.Append(indentation).Append("writer.WriteStartArray(").Append(count).AppendLine(");")
                .Append(indentation).Append("foreach (var item in ").Append(value).AppendLine(")")
                .Append(indentation).AppendLine("{");

            if (property.IsElementNullable)
            {
                b.Append(indentation).AppendLine("    if (item is null) writer.WriteNull();")
                    .Append(indentation).AppendLine("    else")
                    .Append(indentation).AppendLine("    {");

                EmitValueWrite(b, property.ElementKind!.Value, "item" + (property.IsElementNullableValueType ? ".Value" : string.Empty),
                    indentation + "        ", property.ElementEnumUnderlyingKind);

                b.Append(indentation).AppendLine("    }");
            }
            else
            {
                if (property.IsElementReferenceType)
                {
                    b.Append(indentation).AppendLine("    if (item is null) throw new global::System.ArgumentNullException(nameof(item));");
                }

                EmitValueWrite(b, property.ElementKind!.Value, "item", indentation + "    ", property.ElementEnumUnderlyingKind);
            }

            b.Append(indentation).AppendLine("}").Append(indentation).AppendLine("writer.WriteEndArray();");
            return;
        }

        EmitValueWrite(b, property.Kind, value, indentation, property.EnumUnderlyingKind);
    }

    private static void EmitValueWrite(
        StringBuilder b, CborValueKind kind, string value, string indentation,
        CborValueKind? enumUnderlyingKind = null
    )
    {
        switch (kind)
        {
            case CborValueKind.ByteArray:
                b.Append(indentation).Append("writer.WriteByteString(").Append(value).AppendLine(");");
                break;
            case CborValueKind.Enum:
                var underlyingKind = enumUnderlyingKind ?? CborValueKind.Int32;
                var writeMethod = underlyingKind switch
                {
                    CborValueKind.UInt32 => "WriteUInt32",
                    CborValueKind.UInt64 => "WriteUInt64",
                    CborValueKind.Byte or CborValueKind.UInt16 => "WriteUInt32",
                    CborValueKind.Int64 => "WriteInt64",
                    _ => "WriteInt32"
                };

                var castType = underlyingKind switch
                {
                    CborValueKind.Byte or CborValueKind.UInt16 => "uint", CborValueKind.UInt32 => "uint",
                    CborValueKind.UInt64 => "ulong", CborValueKind.SByte or CborValueKind.Int16 => "int",
                    CborValueKind.Int64 => "long", _ => "int"
                };

                b.Append(indentation).Append("writer.").Append(writeMethod).Append("((").Append(castType).Append(")")
                    .Append(value).AppendLine(");");

                break;
            case CborValueKind.Boolean:
                b.Append(indentation).Append("writer.WriteBoolean(").Append(value).AppendLine(");");
                break;
            case CborValueKind.Byte:
                b.Append(indentation).Append("writer.WriteUInt32(").Append(value).AppendLine(");");
                break;
            case CborValueKind.SByte:
                b.Append(indentation).Append("writer.WriteInt32(").Append(value).AppendLine(");");
                break;
            case CborValueKind.Int16:
                b.Append(indentation).Append("writer.WriteInt32(").Append(value).AppendLine(");");
                break;
            case CborValueKind.UInt16:
                b.Append(indentation).Append("writer.WriteUInt32(").Append(value).AppendLine(");");
                break;
            case CborValueKind.Int32:
                b.Append(indentation).Append("writer.WriteInt32(").Append(value).AppendLine(");");
                break;
            case CborValueKind.UInt32:
                b.Append(indentation).Append("writer.WriteUInt32(").Append(value).AppendLine(");");
                break;
            case CborValueKind.Int64:
                b.Append(indentation).Append("writer.WriteInt64(").Append(value).AppendLine(");");
                break;
            case CborValueKind.UInt64:
                b.Append(indentation).Append("writer.WriteUInt64(").Append(value).AppendLine(");");
                break;
            case CborValueKind.Single:
                b.Append(indentation).Append("writer.WriteSingle(").Append(value).AppendLine(");");
                break;
            case CborValueKind.Double:
                b.Append(indentation).Append("writer.WriteDouble(").Append(value).AppendLine(");");
                break;
            case CborValueKind.String:
                b.Append(indentation).Append("writer.WriteTextString(").Append(value).AppendLine(");");
                break;
            case CborValueKind.Bytes:
                b.Append(indentation).Append("writer.WriteByteString(").Append(value).AppendLine(".Span);");
                break;
            default:
                b.Append(indentation).Append(value).AppendLine(".Serialize(writer);");
                break;
        }
    }

    private static string EmitRead(SerializableProperty property, int index, string prefix)
    {
        var propertyName = SyntaxFactory.Literal(property.Name).Text;
        if (property.IsNullable)
        {
            if (property.ConverterTypeName is not null)
            {
                return prefix + "ReadNullableConverted(reader, valueReader => " + EmitPropertyValueRead(property, index, prefix, "valueReader") +
                    ")";
            }

            var method = property.IsNullableValueType ? "ReadNullableValue" : "ReadNullableReference";
            return prefix + method + "(reader, valueReader => " + EmitPropertyValueRead(property, index, prefix, "valueReader") + ")";
        }

        if (property.IsReferenceType)
        {
            return prefix + "ReadNonNull(reader, " + propertyName + ", valueReader => " +
                EmitPropertyValueRead(property, index, prefix, "valueReader") + ")";
        }

        return EmitPropertyValueRead(property, index, prefix, "reader");
    }

    private static string EmitPropertyValueRead(SerializableProperty property, int index, string prefix, string reader)
    {
        if (property.ConverterTypeName is not null)
        {
            var read = prefix + "Converter" + index + ".Read(" + reader + ")";
            return property.IsNullable
                ? read
                : prefix + "ReadConverted(" + SyntaxFactory.Literal(property.Name).Text + ", () => " + read + ")";
        }

        if (property.Kind == CborValueKind.Collection)
        {
            var elementRead = EmitCollectionElementRead(property, prefix);
            var values = prefix + "ReadCollection<" + property.ElementTypeName + ">(" + reader + ", itemReader => " + elementRead + ")";
            return property.CollectionKind == CborCollectionKind.Array
                ? values + ".ToArray()"
                : values;
        }

        return EmitReadValue(prefix, property.Kind, property.ValueTypeName, reader, property.EnumUnderlyingKind,
            SyntaxFactory.Literal(property.Name).Text);
    }

    private static string EmitCollectionElementRead(SerializableProperty property, string prefix)
    {
        var value = EmitReadValue(prefix, property.ElementKind!.Value, property.ElementValueTypeName!, "itemReader",
            property.ElementEnumUnderlyingKind, "\"" + EscapeString(property.Name) + "\"");

        if (property.IsElementNullable)
        {
            var method = property.IsElementNullableValueType ? "ReadNullableValue" : "ReadNullableReference";
            return prefix + method + "(itemReader, valueReader => " +
                EmitReadValue(prefix, property.ElementKind.Value, property.ElementValueTypeName!, "valueReader",
                    property.ElementEnumUnderlyingKind, "\"" + EscapeString(property.Name) + "\"") + ")";
        }

        if (property.IsElementReferenceType)
        {
            return prefix + "ReadNonNull(itemReader, \"" + EscapeString(property.Name) + "\", valueReader => " + value + ")";
        }

        return value;
    }

    private static string EmitReadValue(
        string prefix, CborValueKind kind, string typeName, string reader,
        CborValueKind? enumUnderlyingKind = null, string? propertyName = null
    )
    {
        if (kind == CborValueKind.Enum)
        {
            var underlying = enumUnderlyingKind ?? CborValueKind.Int32;
            var numeric = EmitReadValue(prefix, underlying, typeName, reader, propertyName: propertyName);
            var enumRead = "checked((" + typeName + ")" + numeric + ")";
            return propertyName is null ? enumRead : prefix + "ReadChecked(" + propertyName + ", () => " + enumRead + ")";
        }

        var numericRead = kind switch
        {
            CborValueKind.Byte => "checked((byte)" + reader + ".ReadUInt32())",
            CborValueKind.SByte => "checked((sbyte)" + reader + ".ReadInt32())",
            CborValueKind.Int16 => "checked((short)" + reader + ".ReadInt32())",
            CborValueKind.UInt16 => "checked((ushort)" + reader + ".ReadUInt32())",
            CborValueKind.Int32 => reader + ".ReadInt32()",
            CborValueKind.UInt32 => reader + ".ReadUInt32()",
            CborValueKind.Int64 => reader + ".ReadInt64()",
            CborValueKind.UInt64 => reader + ".ReadUInt64()",
            _ => null
        };

        if (numericRead is not null)
        {
            var read = numericRead;
            if (kind is CborValueKind.Byte or CborValueKind.UInt16 or CborValueKind.UInt32 or CborValueKind.UInt64)
            {
                read = "(" + reader +
                    ".PeekState() == global::System.Formats.Cbor.CborReaderState.NegativeInteger ? throw new global::System.OverflowException() : " +
                    read + ")";
            }

            return propertyName is null ? read : prefix + "ReadChecked(" + propertyName + ", () => " + read + ")";
        }

        return kind switch
        {
            CborValueKind.Boolean => reader + ".ReadBoolean()",
            CborValueKind.Single => reader + ".ReadSingle()",
            CborValueKind.Double => reader + ".ReadDouble()",
            CborValueKind.String => reader + ".ReadTextString()",
            CborValueKind.Bytes => "new global::System.ReadOnlyMemory<byte>(" + reader + ".ReadByteString())",
            CborValueKind.ByteArray => reader + ".ReadByteString()",
            _ => typeName + ".Parse(" + reader + ")"
        };
    }

    internal sealed class CanonicalTextKeyComparer : IComparer<string>
    {
        public static readonly CanonicalTextKeyComparer Instance = new();

        public int Compare(string? x, string? y)
        {
            if (ReferenceEquals(x, y))
            {
                return 0;
            }

            if (x is null)
            {
                return -1;
            }

            if (y is null)
            {
                return 1;
            }

            var xBytes = Encoding.UTF8.GetBytes(x);
            var yBytes = Encoding.UTF8.GetBytes(y);
            var lengthComparison = (xBytes.Length + HeadLength(xBytes.Length)).CompareTo(
                yBytes.Length + HeadLength(yBytes.Length));

            if (lengthComparison != 0)
            {
                return lengthComparison;
            }

            for (var i = 0; i < xBytes.Length; i++)
            {
                var byteComparison = xBytes[i].CompareTo(yBytes[i]);
                if (byteComparison != 0)
                {
                    return byteComparison;
                }
            }

            return 0;
        }

        private static int HeadLength(int length)
        {
            return length < 24 ? 1 :
                length <= byte.MaxValue ? 2 :
                length <= ushort.MaxValue ? 3 : 5;
        }
    }
